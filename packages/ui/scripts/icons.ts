// Fetches every Lucide icon beyond the design system's bundle and writes
// src/icon-paths.extra.gen.ts in the bundle's shape, and the words Lucide tags each icon with to
// src/icon-tags.gen.ts for the picker's search. `bun run icons` in packages/ui; bump VERSION to
// take a newer release. Names the bundle already has are skipped, so its drawings win.
import { ICON_PATHS } from "../src/icon-paths.gen.ts";

const VERSION = "1.55.0";

// One entry per icon, aliases already folded in: name → [[element, attributes], ...].
type IconNodes = Record<string, [string, Record<string, string | number>][]>;

async function fetchJson<T>(file: string): Promise<T> {
  const res = await fetch(`https://unpkg.com/lucide-static@${VERSION}/${file}`);
  if (!res.ok) throw new Error(`lucide-static ${VERSION} ${file}: ${res.status} ${res.statusText}`);
  return (await res.json()) as T;
}
const nodes = await fetchJson<IconNodes>("icon-nodes.json");
const tags = await fetchJson<Record<string, string[]>>("tags.json");

// Same shape as the bundle: self-closing, no space before the slash.
const draw = (parts: IconNodes[string]) =>
  parts
    .map(([tag, attrs]) => {
      const a = Object.entries(attrs)
        .map(([k, v]) => ` ${k}="${v}"`)
        .join("");
      return `<${tag}${a}/>`;
    })
    .join("");

const byName = ([a]: [string, unknown], [b]: [string, unknown]) => a.localeCompare(b);
const paths: string[] = [];
for (const [name, parts] of Object.entries(nodes).sort(byName)) {
  if (Object.hasOwn(ICON_PATHS, name)) continue;
  paths.push(`  ${JSON.stringify(name)}: ${JSON.stringify(draw(parts))},`);
}

const header = (what: string) =>
  `// Generated by scripts/icons.ts from lucide-static ${VERSION} (ISC). Do not edit: bump the
// version in the script and rerun. ${what}`;

await Bun.write(
  new URL("../src/icon-paths.extra.gen.ts", import.meta.url),
  `${header(`Every Lucide icon beyond the design system's bundle
// (icon-paths.gen.ts), so a room, a device or a person can be named by any of them.`)}

export const EXTRA_ICON_PATHS = {
${paths.join("\n")}
} as const;
`,
);

// Only icons the set has, and only words the name does not already say.
const words: string[] = [];
for (const [name, list] of Object.entries(tags).sort(byName)) {
  if (!Object.hasOwn(ICON_PATHS, name) && !Object.hasOwn(nodes, name)) continue;
  const kept = list.filter((word) => !name.includes(word.toLowerCase()));
  if (kept.length) words.push(`  ${JSON.stringify(name)}: ${JSON.stringify(kept.join(" "))},`);
}
await Bun.write(
  new URL("../src/icon-tags.gen.ts", import.meta.url),
  `${header(`The words Lucide tags each icon with, beyond its name,
// so a search for "couch" or "home" finds armchair or house.`)}

export const ICON_TAGS: Record<string, string> = {
${words.join("\n")}
};
`,
);
console.log(
  `wrote ${paths.length} icons and tags for ${words.length} from lucide-static ${VERSION}`,
);
