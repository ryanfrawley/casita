// Generates src/api.gen.ts from proto/api.proto: TypeScript types, message ids, and a trimmed
// protobufjs descriptor, for only the messages this client speaks.
//
//   bun integrations/esphome/scripts/generate.ts

import { join } from "node:path";
import protobuf from "protobufjs";

/** The esphome/esphome commit proto/ was copied from. */
const SOURCE_COMMIT = "fb65096ea3dc4cccf53681b501dec01fd2ec9538";

const MESSAGES = [
  "HelloRequest",
  "HelloResponse",
  "AuthenticationRequest",
  "AuthenticationResponse",
  "DisconnectRequest",
  "DisconnectResponse",
  "PingRequest",
  "PingResponse",
  "DeviceInfoRequest",
  "DeviceInfoResponse",
  "ListEntitiesRequest",
  "ListEntitiesDoneResponse",
  "ListEntitiesBinarySensorResponse",
  "ListEntitiesCoverResponse",
  "ListEntitiesLightResponse",
  "ListEntitiesSensorResponse",
  "ListEntitiesSwitchResponse",
  "ListEntitiesButtonResponse",
  "SubscribeStatesRequest",
  "BinarySensorStateResponse",
  "CoverStateResponse",
  "LightStateResponse",
  "SensorStateResponse",
  "SwitchStateResponse",
  "CoverCommandRequest",
  "LightCommandRequest",
  "SwitchCommandRequest",
  "ButtonCommandRequest",
  "GetTimeRequest",
  "GetTimeResponse",
];

const SCALARS: Record<string, string> = {
  string: "string",
  bool: "boolean",
  bytes: "Uint8Array",
  float: "number",
  double: "number",
  int32: "number",
  uint32: "number",
  sint32: "number",
  fixed32: "number",
  sfixed32: "number",
  int64: "number",
  uint64: "number",
  sint64: "number",
  fixed64: "number",
  sfixed64: "number",
};

const here = join(import.meta.dir, "..");
const root = new protobuf.Root();
for (const file of ["api_options.proto", "api.proto"]) {
  protobuf.parse(await Bun.file(join(here, "proto", file)).text(), root, { keepCase: false });
}

// Walk from the wanted messages to everything they reference.
const types = new Map<string, protobuf.Type>();
const enums = new Map<string, protobuf.Enum>();
const visit = (name: string) => {
  const found = root.lookup(name);
  if (found instanceof protobuf.Enum) {
    enums.set(found.name, found);
  } else if (found instanceof protobuf.Type) {
    if (types.has(found.name)) return;
    types.set(found.name, found);
    for (const field of found.fieldsArray) {
      if (!(field.type in SCALARS)) visit(field.type);
    }
  } else {
    throw new Error(`${name} is not in api.proto`);
  }
};
for (const name of MESSAGES) visit(name);

const descriptor: Record<string, unknown> = {};
const lines: string[] = [];
for (const e of enums.values()) {
  descriptor[e.name] = { values: e.values };
  lines.push(`export const ${e.name} = ${JSON.stringify(e.values, null, 2)} as const;`, "");
}
for (const t of types.values()) {
  descriptor[t.name] = {
    fields: Object.fromEntries(
      t.fieldsArray.map((f) => [
        f.name,
        { type: f.type, id: f.id, ...(f.repeated ? { rule: "repeated" } : {}) },
      ]),
    ),
  };
  lines.push(`export interface ${t.name} {`);
  for (const f of t.fieldsArray) {
    // Enums travel as their numeric value.
    const base = SCALARS[f.type] ?? (enums.has(f.type) ? "number" : f.type);
    const message = types.has(f.type);
    lines.push(
      `  ${f.name}${message && !f.repeated ? "?" : ""}: ${base}${f.repeated ? "[]" : ""};`,
    );
  }
  lines.push("}", "");
}

const ids = MESSAGES.map((name) => {
  const id = types.get(name)?.options?.["(id)"];
  if (typeof id !== "number") throw new Error(`${name} has no (id) option`);
  return `  ${name}: ${id},`;
});

const output = `// Generated by scripts/generate.ts from esphome/esphome@${SOURCE_COMMIT}
// (esphome/components/api/api.proto). Do not edit; see proto/README.md.

export const SOURCE_COMMIT = "${SOURCE_COMMIT}";

${lines.join("\n")}
/** Every message this client sends or understands, by name. */
export interface Messages {
${MESSAGES.map((name) => `  ${name}: ${name};`).join("\n")}
}

/** The wire type id of each message (its \`(id)\` option). */
export const MESSAGE_IDS = {
${ids.join("\n")}
} as const satisfies Record<keyof Messages, number>;

/** protobufjs descriptor for the messages above. */
export const DESCRIPTOR = ${JSON.stringify({ nested: descriptor }, null, 2)};
`;
await Bun.write(join(here, "src", "api.gen.ts"), output);
console.log(`Wrote src/api.gen.ts: ${types.size} messages, ${enums.size} enums`);
